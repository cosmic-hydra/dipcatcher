"""Guards for hashed locks, advisory floors, and live-broker fail-closed."""

from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]


def test_requirements_lock_exists_and_is_hashed() -> None:
    lock = REPO_ROOT / "requirements.lock.txt"
    assert lock.is_file(), "run make requirements-lock"
    text = lock.read_text(encoding="utf-8")
    assert text.startswith("# This file was autogenerated by uv")
    assert "--hash=sha256:" in text
    assert "\naiohttp==" in text


def test_security_constraint_floors_cover_audited_advisories() -> None:
    """constraint-dependencies must keep make-audit fix versions from regressing."""

    text = (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8")
    floors = {
        "urllib3": "2.8.0",
        "virtualenv": "21.14.9",
        "aiohttp": "3.14.4",
        "certifi": "2026.10.19",
        "pillow": "13.0.0",
        "yarl": "1.25.1",
    }
    for name, version in floors.items():
        assert re.search(rf'"{name}>={re.escape(version)}"', text), name


def test_alpaca_live_exchange_refuses_before_http() -> None:
    """Honesty contract: alpaca-live must raise LiveBrokerRefused in _exchange."""

    source = (REPO_ROOT / "src/quant_fund/live/brokers.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    exchange = None
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, ast.FunctionDef) and item.name == "_exchange":
                    exchange = item
                    break
    assert exchange is not None
    dumped = ast.dump(exchange)
    assert "LiveBrokerRefused" in dumped
    assert "alpaca-live" in dumped


